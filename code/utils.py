from typing import Union, List, Optional, Literal
import numpy as np

import pynwb

from spikeinterface import BaseRecording, SortingAnalyzer, ChannelSparsity


def _get_electrode_group_indices_by_channel(recording, nwbfile):
    """
    Like neuroconv's _get_electrode_group_indices but returns one NWB electrode index
    per recording channel, in recording channel order, disambiguating by channel_name.
    This is required for NP1.0 files that store 384 AP + 96 LF electrodes in the same
    table: group_name alone is ambiguous, and order must match the template array axes.
    """
    if "group_name" in recording.get_property_keys():
        group_names = {str(g) for g in recording.get_property("group_name")}
    elif "group" in recording.get_property_keys():
        group_names = {str(g) for g in recording.get_property("group")}
    else:
        return None

    channel_names_prop = recording.get_property("channel_name")
    if channel_names_prop is None:
        recording_channel_names = recording.get_channel_ids().astype(str)
    else:
        recording_channel_names = np.asarray(channel_names_prop, dtype=str)

    electrodes_df = nwbfile.electrodes.to_dataframe()
    # Build channel_name -> NWB index lookup, restricted to matching groups
    # compare without spaces: the rig device name ("Probe A") can differ from the one in the NWB ("ProbeA")
    nwb_group_names = electrodes_df["group_name"].astype(str).str.replace(" ", "")
    filtered_df = electrodes_df[nwb_group_names.isin({g.replace(" ", "") for g in group_names})]
    channel_name_to_index = {str(ch): idx for idx, ch in zip(filtered_df.index, filtered_df["channel_name"])}

    # One index per recording channel, preserving recording channel order
    return np.array([channel_name_to_index[ch] for ch in recording_channel_names])


def add_waveforms_with_uneven_channels(
    sorting_analyzer: SortingAnalyzer,
    recording: BaseRecording = None,
    nwbfile: Optional[pynwb.NWBFile] = None,
    metadata: Optional[dict] = None,
    unit_ids: Optional[List[Union[str, int]]] = None,
    skip_properties: Optional[List[str]] = None,
    property_descriptions: Optional[dict] = None,
    write_as: Literal["units", "processing"] = "units",
    units_name: str = "units",
    units_description: str = "Autogenerated by neuroconv.",
    write_waveforms: bool = True,
    num_channels_max: Optional[int] = None,
):
    """
    Modified version of the neurconv.tools.spikeinterface.add_waveforms function
    to deal with multiple streams with an uneven number of channels (due to bad channel removel).
    The strategy is to write sparse templates: each unit gets its `num_channels_max` closest channels
    (all analyzer channels if None), and its `electrodes` point to those channels.
    """
    from neuroconv.tools.spikeinterface.spikeinterface import (
        add_electrodes_to_nwbfile,
        _add_units_table_to_nwbfile,
    )

    # TODO: move into add_units
    assert write_as in [
        "units",
        "processing",
    ], f"Argument write_as ({write_as}) should be one of 'units' or 'processing'!"
    if write_as == "units":
        assert units_name == "units", "When writing to the nwbfile.units table, the name of the table must be 'units'!"
    write_in_processing_module = False if write_as == "units" else True

    num_units = len(sorting_analyzer.unit_ids)
    sorting = sorting_analyzer.sorting

    if write_waveforms:
        template_ext = sorting_analyzer.get_extension("templates")
        dense_means = template_ext.get_templates()
        dense_stds = template_ext.get_templates(operator="std")
        # every unit gets the same number of (closest) channels, so that waveform_mean/sd is a 3D array
        num_channels = num_channels_max or sorting_analyzer.get_num_channels()
        sparsity = ChannelSparsity.from_closest_channels(sorting_analyzer, num_channels=num_channels)
        template_means = np.stack([dense_means[i][:, mask] for i, mask in enumerate(sparsity.mask)])
        template_stds = np.stack([dense_stds[i][:, mask] for i, mask in enumerate(sparsity.mask)])
        unit_channel_ids = [sorting_analyzer.channel_ids[mask] for mask in sparsity.mask]
    else:
        template_means = None
        template_stds = None
        unit_electrode_indices = None

    if unit_ids is None:
        unit_ids = sorting_analyzer.unit_ids

    # metrics properties (quality, template) are added as properties to the sorting copy
    sorting_copy = sorting.select_units(unit_ids=unit_ids)
    property_descriptions = property_descriptions or {}

    if sorting_analyzer.has_extension("quality_metrics"):
        qm_ext = sorting_analyzer.get_extension("quality_metrics")
        qm_df = qm_ext.get_data()
        qm_descriptions = qm_ext.get_metric_column_descriptions()

        for prop in qm_df.columns:
            if prop not in sorting_copy.get_property_keys():
                sorting_copy.set_property(prop, qm_df.loc[unit_ids, prop].values)
                property_descriptions.update({prop: qm_descriptions.get(prop, "No description.")})

    if sorting_analyzer.has_extension("template_metrics"):
        tm_ext = sorting_analyzer.get_extension("template_metrics")
        tm_df = tm_ext.get_data()
        tm_descriptions = tm_ext.get_metric_column_descriptions()
        for prop in tm_df.columns:
            if prop not in sorting_copy.get_property_keys():
                sorting_copy.set_property(prop, tm_df.loc[unit_ids, prop].values)
                property_descriptions.update({prop: tm_descriptions.get(prop, "No description.")})

    # add electrodes only if needed
    if nwbfile.electrodes is None and write_waveforms:
        add_electrodes_to_nwbfile(recording, nwbfile=nwbfile, metadata=metadata)
    electrode_indices = _get_electrode_group_indices_by_channel(recording, nwbfile=nwbfile)

    available_nwb_groups = np.unique(nwbfile.electrodes["group_name"][:])
    available_recording_groups = np.unique(recording.get_channel_groups())

    if write_waveforms:
        if electrode_indices is None or len(electrode_indices) == 0:
            print(
                f"Could not find electrode indices for templates: waveform_mean/sd will not be added to NWB.\n"
                f"Groups in NWB: {available_nwb_groups} - Groups in recording: {available_recording_groups}."
            )
            template_means = None
            template_stds = None
            unit_electrode_indices = None
        else:
            # electrode_indices follow the recording channels, the analyzer channels are a subset of them
            recording_channel_positions = {ch: i for i, ch in enumerate(recording.channel_ids)}
            unit_electrode_indices = [
                [electrode_indices[recording_channel_positions[ch]] for ch in channel_ids]
                for channel_ids in unit_channel_ids
            ]
            if unit_ids is not None:
                unit_indices = sorting.ids_to_indices(unit_ids)
                template_means = template_means[unit_indices]
                template_stds = template_stds[unit_indices]
                unit_electrode_indices = [unit_electrode_indices[i] for i in unit_indices]

    _add_units_table_to_nwbfile(
        sorting=sorting_copy,
        nwbfile=nwbfile,
        unit_ids=unit_ids,
        property_descriptions=property_descriptions,
        skip_properties=skip_properties,
        write_in_processing_module=write_in_processing_module,
        units_table_name=units_name,
        unit_table_description=units_description,
        waveform_means=template_means,
        waveform_sds=template_stds,
        unit_electrode_indices=unit_electrode_indices,
        waveform_rate=sorting_copy.sampling_frequency,
        waveform_unit="microvolts",
        resolution=1.0 / sorting_copy.sampling_frequency
    )
